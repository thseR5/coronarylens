"""Data audit: `uv run python -m ml.audit` -> reports/data_audit.md.

Every fact is recomputed from the xlsx. The "claimed" column quotes the project brief so drift is visible; it is never
used as data.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from ml import config
from ml.evaluate import auc
from ml.ingest import data_sha256, load_dataset
from ml.leakage import proxy_scan

CLAIMS = {
    "shape": "303×59", "missing": "0", "CAD": "216", "LAD": "177", "LCX": "119", "RCA": "114",
    "patterns": "000:86 100:57 111:63 110:33 101:24 001:17 010:13 011:10",
    "cad_equals_any_vessel": "302/303 (row 93)", "sex_values": "Male/Fmale", "constant": "Exertional CP",
    "rare": "CHF 1, LowTH Ang 2, CVA 5, Weak Peripheral Pulse 5, CRF 6", "BBB": "N, LBBB, RBBB",
    "VHD": "N, mild, Moderate, Severe",
}


def run() -> str:
    fcfg, tcfg = config.features_cfg(), config.targets_cfg()
    ds = load_dataset(fcfg, tcfg)
    raw, X, T = ds.raw, ds.X, ds.T
    anyv = T[["LAD", "LCX", "RCA"]].max(axis=1)
    mismatch = [int(i) for i in np.where(anyv != T["cad"])[0]]
    pc = T["pattern"].value_counts()
    text_cols = [c for c in raw.columns if not pd.api.types.is_numeric_dtype(raw[c])]
    yn_cols = [c for c in text_cols if set(raw[c].astype(str).unique()) <= {"Y", "N"}]
    int01 = [c for c in raw.columns if pd.api.types.is_numeric_dtype(raw[c]) and set(raw[c].unique()) <= {0, 1}]
    const = [c for c in raw.columns if raw[c].nunique() == 1]
    rare = []
    for f in fcfg["features"]:
        if f["type"] == "binary":
            pos = int(X[f["id"]].sum())
            n_min = min(pos, len(X) - pos)
            if n_min <= 10:
                rare.append((f["id"], f["column"], n_min))
    for c in ("bbb_LBBB", "bbb_RBBB"):
        rare.append((c, "BBB", int(X[c].sum())))
    computed = {
        "shape": f"{raw.shape[0]}×{raw.shape[1]}", "missing": str(int(raw.isna().sum().sum())),
        "CAD": str(int(T["cad"].sum())), "LAD": str(int(T["LAD"].sum())), "LCX": str(int(T["LCX"].sum())),
        "RCA": str(int(T["RCA"].sum())),
        "patterns": " ".join(f"{p}:{int(pc.get(p, 0))}" for p in ["000", "100", "111", "110", "101", "001", "010",
                                                                     "011"]),
        "cad_equals_any_vessel": f"{int((anyv == T['cad']).sum())}/{len(T)} (row {', '.join(map(str, mismatch))})",
        "sex_values": "/".join(sorted(raw["Sex"].astype(str).unique(), key=lambda s: s != "Male")),
        "constant": ", ".join(const),
        "rare": ", ".join(f"{col} {n}" for _, col, n in sorted(rare, key=lambda r: r[2]) if n <= 6 and col != "BBB"),
        "BBB": ", ".join(sorted(raw["BBB"].astype(str).unique(), key=["N", "LBBB", "RBBB"].index)),
        "VHD": ", ".join(sorted(raw["VHD"].astype(str).unique(), key=["N", "mild", "Moderate", "Severe"].index)),
    }
    row93 = raw.iloc[mismatch[0]][["Cath", "LAD", "LCX", "RCA"]].to_dict() if mismatch else {}

    L = ["# Data audit (generated by `python -m ml.audit`)", "",
         f"Source: `{config.DATA_PATH.relative_to(config.ROOT)}`, SHA-256 `{data_sha256()}`.", "",
         "## Verified facts (recomputed from the data)", "", "| fact | computed from data | claimed in the project brief | match |",
         "|---|---|---|---|"]
    for k, v in computed.items():
        L.append(f"| {k} | {v} | {CLAIMS[k]} | {'yes' if v == CLAIMS[k] else '**NO**'} |")
    L += ["", f"Label inconsistency row(s) {mismatch}: {row93}. `Cath` stays the CAD ground truth.", "",
          (f"Text (string-dtype) columns: {len(text_cols)}; of which Y/N: {len(yn_cols)}. Numeric 0/1 columns: "
          f"{len(int01)}. Encoded model matrix: {X.shape[1]} columns (BBB one-hot, VHD ordinal 0-3)."), "",
          "## Feature ranges vs config plausibility bounds", "", ("| feature | min | median | max | config range | "
          "inside |"), "|---|---|---|---|---|---|"]
    for f in fcfg["features"]:
        if f["type"] == "numeric":
            x = X[f["id"]]
            ok = f["range"][0] <= x.min() and x.max() <= f["range"][1]
            L.append(f"| {f['id']} | {x.min():g} | {x.median():g} | {x.max():g} | {f['range']} | {'yes' if ok else 'NO'} |")
    L += ["", "## Rare binary features (minority count ≤ 10)", "", "| feature | column | minority count |",
          "|---|---|---|"]
    L += [f"| {fid} | {col} | {n} |" for fid, col, n in sorted(rare, key=lambda r: r[2])]
    L += ["", ("## Univariate ROC-AUC per feature and target (full data, descriptive only; direction-free = "
              "max(AUC, 1-AUC) in parentheses)"), "", "| feature | CAD | LAD | LCX | RCA |", "|---|---|---|---|---|"]
    rows = []
    for c in X.columns:
        a = {t: auc(T[col].to_numpy(), X[c].to_numpy()) for t, col in
             [("CAD", "cad"), ("LAD", "LAD"), ("LCX", "LCX"), ("RCA", "RCA")]}
        rows.append((max(max(v, 1 - v) for v in a.values()), c, a))
    for _, c, a in sorted(rows, key=lambda r: -r[0]):
        L.append(f"| {c} | " + " | ".join(f"{v:.3f} ({max(v, 1 - v):.3f})" for v in a.values()) + " |")
    L += ["", "## Leakage proxy scan", "",
          "In-fold (5-fold, training folds only) univariate direction-free AUC > 0.95 flags a possible label proxy.", ""]
    for t, col in [("CAD", "cad"), ("LAD", "LAD"), ("LCX", "LCX"), ("RCA", "RCA")]:
        flags = proxy_scan(X, T[col].to_numpy(), seed=config.seed())
        L.append(f"- {t}: {'no feature flagged' if not flags else flags}")
    L += ["", (f"Forbidden columns `{tcfg['forbidden_columns']}` are absent from the model matrix (asserted by "
              "`ml.leakage.assert_clean` at ingest, training and inference).")]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = config.REPORTS / "data_audit.md"
    out.write_text(run(), encoding="utf-8")
    print(f"wrote {out}")
