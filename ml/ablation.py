"""Leakage ablation (analysis only, never served): `uv run python -m ml.ablation`.

Shows how common shortcuts inflate reported accuracy on this dataset:
  A. SMOTE on the full data + feature selection on the full data, then 10-fold CV   (leaky, as often published)
  B. feature selection on the full data, then CV                                    (selection leak only)
  C. SMOTE on the full data, then CV                                                (oversampling leak only)
  D. correct: selection (and optional SMOTE) fitted inside each training fold only
Same model (random forest, 300 trees), same 10x3 repeated stratified CV, all 303 patients.
"""

from __future__ import annotations

import json

import numpy as np
from imblearn.over_sampling import SMOTE
from imblearn.pipeline import Pipeline as ImbPipeline
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_selection import SelectKBest, f_classif
from sklearn.model_selection import RepeatedStratifiedKFold, cross_validate
from sklearn.pipeline import Pipeline

from ml import config
from ml.ingest import load_dataset

K_FEATURES = 20


def _rf(seed):
    return RandomForestClassifier(300, random_state=seed, n_jobs=1)


def run(n_jobs: int = 4) -> dict:
    seed = config.seed()
    ds = load_dataset()
    X = ds.X.to_numpy(dtype=float)
    cv = RepeatedStratifiedKFold(n_splits=10, n_repeats=3, random_state=seed)
    scoring = ["roc_auc", "accuracy"]
    out: dict = {"model": "RandomForest(300)", "cv": "10-fold x 3 repeats, stratified", "k_features": K_FEATURES,
                 "targets": {}}
    for target, col in [("CAD", "cad"), ("LCX", "LCX"), ("RCA", "RCA")]:
        y = ds.T[col].to_numpy()
        res = {}

        def score(name, Xs, ys, est, res=res):
            r = cross_validate(est, Xs, ys, cv=cv, scoring=scoring, n_jobs=n_jobs)
            res[name] = {m: {"mean": float(np.mean(r[f"test_{m}"])), "sd": float(np.std(r[f"test_{m}"], ddof=1))}
                         for m in scoring}

        Xs_sm, ys_sm = SMOTE(random_state=seed).fit_resample(X, y)
        sel_sm = SelectKBest(f_classif, k=K_FEATURES).fit(Xs_sm, ys_sm)
        score("A_smote_and_selection_before_cv", sel_sm.transform(Xs_sm), ys_sm, _rf(seed))
        sel = SelectKBest(f_classif, k=K_FEATURES).fit(X, y)
        score("B_selection_before_cv", sel.transform(X), y, _rf(seed))
        score("C_smote_before_cv", Xs_sm, ys_sm, _rf(seed))
        score("D_correct_selection_in_fold", X, y,
              Pipeline([("sel", SelectKBest(f_classif, k=K_FEATURES)), ("rf", _rf(seed))]))
        score("D_correct_selection_and_smote_in_fold", X, y,
              ImbPipeline([("sel", SelectKBest(f_classif, k=K_FEATURES)), ("smote", SMOTE(random_state=seed)),
                           ("rf", _rf(seed))]))
        out["targets"][target] = res
    return out


def write(out: dict) -> None:
    (config.ARTIFACTS / "ablation.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Leakage ablation (analysis only; never served)", "",
         ("Same random forest and repeated 10-fold CV on all 303 patients; only the protocol changes. "
         "Protocols A-C fit SMOTE and/or feature selection on the full dataset before splitting, so test folds "
         "influence training (SMOTE also places synthetic copies interpolated from test patients into training "
         "folds). D fits everything inside training folds."), "",
         "| target | protocol | ROC-AUC (mean ± SD) | accuracy (mean ± SD) |", "|---|---|---|---|"]
    for t, res in out["targets"].items():
        for name, r in res.items():
            L.append(f"| {t} | {name} | {r['roc_auc']['mean']:.3f} ± {r['roc_auc']['sd']:.3f} | "
                     f"{r['accuracy']['mean']:.3f} ± {r['accuracy']['sd']:.3f} |")
    L += ["", "Generated by `uv run python -m ml.ablation`."]
    (config.REPORTS / "leakage_ablation.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    write(run())
